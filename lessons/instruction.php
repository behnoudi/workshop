### اصل سوم: صریح باشد (Explicitness)

در مکالمات روزمره، ما اغلب از تعارفات و جملات غیرمستقیم استفاده می‌کنیم. مثلاً به جای اینکه بگوییم «در را ببند»، ممکن است بگوییم «هوا سرد است.». این روش برای ارتباطات انسانی بد نیست، اما برای هوش مصنوعی می‌تواند گیج‌کننده باشد.

وقتی به مدل دستور می‌دهید، بسیار **«صریح»** منظورتان را بگویید. اگر درخواست شما مبهم باشد، به احتمال زیاد پاسخ خوبی دریافت نمی‌کنید. هرچقدر پرامپت شما بی‌پرده‌تر و رک‌تر باشد، نتیجه بهتری می‌گیرید. از جملات اضافی که به انجام وظیفه اصلی کمکی نمی‌کنند، پرهیز کنید.

**مثال مبهم:** «می‌توانی لطفاً به من کمک کنی که این متن را خلاصه کنم؟».
**مثال صریح:** «این متن را خلاصه کن».

جمله‌ی اول حاوی کلمات و عباراتی است که برای مدل هوش مصنوعی ضرورتی ندارد. اگرچه هوش مصنوعی احتمالا تعارفات شما را متوجه می‌شود، اما مستقیم صحبت کردن به کاهش مصرف **«توکن»** و سرعت بالاتر دریافت پاسخ کمک می‌کند. بنابراین جمله‌ی دوم، مستقیم و بدون هیچ حاشیه‌ای، وظیفه را مشخص می‌کند و احتمال دریافت یک پاسخ دقیق و مرتبط را به شدت افزایش می‌دهد.

