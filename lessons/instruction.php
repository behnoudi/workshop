### تمرین‌های تثبیت مهارت

#### تمرین ۱: افزودن جزئیات
پرامپت زیر را به یک دستور کار **«امری»**، **«دقیق»**، **«صریح»** و **«ایمن»** تبدیل کنید:
> به اطلاعاتی درباره سیاره مریخ نیاز دارم.

**راهنمایی:** به مواردی مانند جنبه‌های خاصی از مریخ (مانند اتمسفر، نیروی جاذبه، وجود آب، …) که می‌خواهید درباره‌اش بدانید، فکر کنید.

#### تمرین ۲: خلق یک داستان
با استفاده از اصولی که یاد گرفتید، یک **«دستور کار»** بنویسید که از هوش مصنوعی بخواهد یک پاراگراف داستانی کوتاه (حدود ۲۰۰ کلمه) بسازد. در دستور کار خود، این موارد را مشخص کنید:
- **شخصیت اصلی:** یک ربات کاوشگر کنجکاو.
- **مکان:** یک جنگل بیگانه با گیاهان درخشان.
- **نقطه‌ی عطف داستان:** ربات چیزی غیرمنتظره پیدا می‌کند.

#### تمرین ۳: معلم خصوصی شما
فرض کنید می‌خواهید مفهوم **«فتوسنتز»** را برای یک کودک توضیح دهید. یک **«دستور کار»** بنویسید که از هوش مصنوعی بخواهد این مفهوم پیچیده را با استفاده از **«آنالوژی»** به زبان ساده و قابل فهم برای کودکان شرح دهد.
