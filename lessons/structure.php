> - خروجی باید با لحن آموزشی و جذاب باشد.  
> - خروجی باید حدود ۱۰۰۰ کلمه باشد.  
> 
> **ساختار خروجی (Structure):**  
> - **بخش اول:** تعریف فرهنگ  
> - **بخش دوم:** اجزای فرهنگ (فرهنگ مادی / فرهنگ غیرمادی)  
> - **بخش سوم:** اهمیت و نقش فرهنگ  
