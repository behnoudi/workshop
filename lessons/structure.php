- **گام اول:** با یک پرامپت ساده شروع کنید (مثلاً: «یک داستان درباره سفر نوجوان به جزیره بنویس»).
- **گام دوم:** جزئیات شخصیتی، زمانی و مکانی را به متن اضافه کنید.
- **گام سوم:** پرامپت نهایی را به صورت کاملاً ساختاریافته با مارک‌داون (نقش، هدف، دستور کار، فرمت و ساختار) تدوین کنید.

