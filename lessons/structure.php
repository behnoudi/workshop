### مقایسه دو رویکرد: پرامپت ساده در برابر ساختاریافته

برای مثال، تصور کنید می‌خواهید برای تدریس آماده شوید:

**پرامپت ساده:**
> به عنوان معلم مطالعات اجتماعی نهم، یک درسنامه درباره مفهوم «فرهنگ» بنویس. این درسنامه باید به ترتیب شامل تعریف فرهنگ، اجزای آن، اهمیت و نقش آن، چگونگی یادگیری و پویایی و تغییر فرهنگ باشد. برای جذابیت بیشتر، از عنوان‌های کوتاه و مثال استفاده کن. متن را با لحنی آموزشی و به زبان فارسی روان ارائه کن.

**پرامپت ساختاریافته:**
> **نقش (Role):** شما یک معلم مطالعات اجتماعی باتجربه هستید.  
> **مخاطب (Audience):** دانش‌آموزان پایه نهم  
> **هدف (Goal):** آموزش مفهوم فرهنگ.  
> **دستورکار (Task):** یک درسنامه درباره «فرهنگ» با رعایت موارد زیر بنویسید:  
> - برای هر بخش از عنوان‌هایی جذاب و کوتاه استفاده کنید.  
> - هنگام توضیح مفاهیم کلی، از مثال‌های مرتبط با زندگی روزمره مخاطبان استفاده کنید.  
> - هنگام توضیح مفاهیم انتزاعی پیچیده، از آنالوژی (تشبیه) استفاده کنید.  
> 
> **فرمت خروجی (Format):**  
