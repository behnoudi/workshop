### بخش سوم: ۵ گام طلایی برای تسلط بر مهندسی پرامپت

- **۱. با تعیین هدف شروع کنید:** قبل از نوشتن، از خود بپرسید: «دقیقاً چه می‌خواهم؟» یک خلاصه؟ یک لیست؟ یک جدول؟ هدف شما، بهترین ساختار پرامپت را مشخص می‌کند.
- **۲. با یک پرامپت ساده شروع کرده و تکرار (Iteration) کنید:** با پرامپت‌های ساده کارتان را آغاز کنید و با تحلیل خروجی، کم‌کم جزئیات بیشتری به آن اضافه کنید. پرامپت‌نویسی یک فرآیند تکرارپذیر آزمون و خطاست.
- **۳. جزئیات شفاف بیفزایید:** چند دقیقه صرف زمان برای ساختاربندی دقیق پرامپت، بسیار باارزش‌تر از ساعت‌ها کلنجار رفتن با خروجی‌های نامطلوب است.
- **۴. معادل انگلیسی اصطلاحات را ذکر کنید:** برای کلمات کلیدی، معادل انگلیسی آن‌ها را در پرانتز بنویسید؛ مانند: **هدف (Goal)** یا **دستورکار (Task)**. این کار ابهام مدل‌های زبانی را به صفر می‌رساند.
- **۵. به دنبال نتایج تکرارپذیر باشید:** ساختارمند کردن پرامپت‌ها باعث می‌شود در دفعات مختلف اجرای دستور، پاسخ‌هایی با کیفیت یکدست و قابل‌اعتماد دریافت کنید. پرامپت‌های موفق خود را ذخیره کنید تا به عنوان الگو از آن‌ها بهره ببرید.

