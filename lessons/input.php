### بخش اول: انواع داده‌های ورودی (Types of Input Data)

در دنیای دیجیتال، داده‌های ورودی که به هوش مصنوعی می‌دهید معمولاً به دو دسته تقسیم می‌شوند:

- **داده‌های غیرساختاریافته (Unstructured Data):** داده‌هایی که فرمت منظم یا جدولی ندارند؛ مانند یک متن طولانی برای خلاصه‌سازی، یک کد برنامه‌نویسی برای عیب‌یابی، یا یک تصویر برای تحلیل.
- **داده‌های ساختاریافته (Structured Data):** داده‌هایی که کاملاً منظم و سازماندهی‌شده هستند؛ مانند جدول نمرات کلاسی، آمار عددی فروش ماهانه.

---

### بخش دوم: ترفند مهندسی برچسب‌گذاری داده‌ها (Data Labeling)

یکی از چالش‌های بزرگ کاربران تازه‌کار این است که دستور کار خود را با داده‌های ورودی مخلوط می‌کنند و این کار باعث گیج شدن هوش مصنوعی می‌شود.

به عنوان یک مهندس پرامپت حرفه‌ای، همیشه قبل از ارائه داده‌های ورودی، از یک **«برچسب» (Label)** یا خطوط جداکننده استفاده کنید تا مرز بین دستور کار شما و داده‌هایتان کاملاً مشخص باشد. این کار کیفیت و سرعت پاسخ‌دهی را به شدت افزایش می‌دهد.

**نمونه‌هایی از داده‌های ورودی برچسب‌گذاری شده:**

> **# متن ورودی:** [متنی که می‌خواهید خلاصه یا ترجمه شود را در این بخش قرار دهید.]  
> **# داده‌های عددی:** [جدول یا آماری که می‌خواهید تحلیل شود را در این بخش بنویسید.]  
> **# کد برنامه‌نویسی:** [کدی را که می‌خواهید اشکال‌زدایی یا بهینه‌سازی شود در این بخش کپی کنید.]  
> **# تصویر ورودی:** [تصویر مورد نظرتان را برای تحلیل و توصیف ویژگی‌های آن آپلود کنید.]  
> **# کلیدواژه‌های طلایی:** [واژه‌های خاصی که می‌خواهید حتماً در تولید خروجی به کار روند را در اینجا بنویسید.]

