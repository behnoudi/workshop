### تمرین‌های تثبیت مهارت

#### تمرین کارگاهی: طراحی پرامپت برچسب‌گذاری‌شده و متغیر
یک پرامپت برای نوشتن یک متن تبلیغاتی و متقاعدکننده برای یک محصول ورزشی طراحی کنید.

پرامپت خود را دقیقاً بر اساس الگوی ساختاریافته و برچسب‌گذاری‌شده زیر بنویسید و خروجی آن را ارزیابی کنید:

**الگوی پرامپت:**
> **# دستور کار:** یک متن تبلیغاتی کوتاه، پرانرژی و متقاعدکننده بنویسید.  
> **# مخاطب:** نوجوانان و ورزشکاران دبیرستانی.  
> **# داده‌های ورودی:**  
> **– نام محصول:** کفش ورزشی آلفا-سیستم  
> **– کلیدواژه‌ها:** سرعت، راحتی فوق‌العاده، طراحی آینده‌نگرانه

**گام تکمیلی:** اکنون «داده‌های ورودی» (مثلاً نام محصول و کلیدواژه‌ها) را به یک محصول کاملاً متفاوت تغییر دهید و تفاوت چشمگیر خروجی‌ها را بررسی کنید.
