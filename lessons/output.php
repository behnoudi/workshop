### مؤلفه دوم: ساختار (Structure)

در این بخش باید چیدمان منطقی و سازماندهی محتوای خروجی را مشخص کنید.

یعنی به هوش مصنوعی می‌گویید که اطلاعات چگونه باید بخش‌بندی شوند و نحوه‌ی ارائه‌ی آن‌ها چگونه باشد و هر بخش شامل چه نوع داده‌ای است.

> **– عنوان:** [عنوان (Title)]  
> **– نویسنده:** [نام نویسنده (Author)]  
> **– بیوگرافی نویسنده:** [پیشینه‌ی نویسنده (Author’s Biography) متن]  
> **– حوزه‌ی مطالعاتی:** [حداکثر سه مورد از اصلی‌ترین حوزه‌های مطالعاتی (Field of Study) متن (مانند: روانشناسی، ادبیات و غیره)]  
> **– اصطلاحات:** [اصطلاحات کلیدی (Terminology) و معادل فارسی آن در قالب بولت پوینت]

