### تمرین‌های تثبیت مهارت

#### تمرین ۱: تغییر لحن خروجی (Tone)
دو پرامپت جداگانه برای موضوع **«فوایدِ صبحِ زود بیدار شدن»** بنویسید:
- با لحن انگیزشی و پرشور
- با لحن طنزآمیز

خروجی‌های هر دو پرامپت را مقایسه کنید و ببینید تغییر لحن چگونه حس و پیام متن را دگرگون می‌کند.

---

#### تمرین ۲: ساختاربندی و جدول‌سازی محتوا (Structure)
