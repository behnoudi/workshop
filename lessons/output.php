### مؤلفه اول: فرمت (Format)

در این بخش باید تمام جزئیاتی را که برای نحوه‌ی نمایش پاسخ هوش مصنوعی مهم هستند مشخص کنید.

با مشخص کردن دقیق فرمت، شما به هوش مصنوعی می‌گویید که پاسخ خود را چگونه ارائه کند، از چه قالبی (مانند لیست‌ها، جدول، کد، یا متن ساده) استفاده کند و چه سبک نوشتاری را به کار ببرد.

> **– زبان (Language):** پاسخ را به زبان فارسی روان بنویسید.  
> **– سبک (Style):** پاسخ را به سبک رسمی بنویسید. (شیوه‌ی کلی نگارش مثل: رسمی، محاوره‌ای، علمی، تحلیلی، روایی یا غیره)  
> **– لحن (Tone):** پاسخ را با لحن محترمانه بنویسید. (احساس یا نگرش نویسنده مثل: محترمانه، انگیزشی، حزن‌آلود، طنزآمیز، همدلانه یا غیره)  
> **– طول خروجی (Output Length):** پاسخ باید در حدود سه پاراگراف و حداکثر ۲۵۰ کلمه باشد.  
> **– میزان بسط مسئله (Level of Detail):**  
> **نمای کلی (High-level):** «موضوع را به صورت کلی و بدون ورود به جزییات فنی توضیح دهید.»  
> **موشکافانه (Deep-dive):** «موضوع را با تمام جزییات ریز، مراحل فرعی و همه‌جانبه بسط بده.»  
> **– سطح شناختی (Cognitive Level):**  
> **دانش و درک ساده (LOTS):** «فقط مفهوم را تعریف کن و یک مثال ساده بزن.»  
> **تحلیل و ارزیابی منتقدانه (HOTS):** «موضوع را تحلیل کن، نقاط قوت و ضعف آن را مقایسه کرده و در نهایت ارزیابی خودت را بنویس.»

