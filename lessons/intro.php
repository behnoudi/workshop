### بخش سوم: کالبدشکافی یک نمونه واقعی (Prompt Dissection)

**پرامپت نمونه:**
> متن را به مثبت، منفی یا خنثی دسته‌بندی کن.  
> متن: فکر می‌کنم غذا معمولی بود.  
> احساسات:

**کالبدشکافی اجزا:**
> **# دستور کار:** «متن را به مثبت، منفی یا خنثی دسته‌بندی کن».  
> **# داده ورودی:** «فکر می‌کنم غذا معمولی بود.»  
> **# ویژگی‌های خروجی:** «احساسات:»  
> **# زمینه:** ندارد  

همانطور که مشاهده می‌کنید، لازم نیست هر پرامپتی الزاماً دارای همه‌ی این چهار عنصر به صورت هم‌زمان باشد؛ بلکه متناسب با هدف شما تنظیم می‌شود.

