### تمرین‌های تثبیت مهارت

#### تمرین کارگاهی: کالبدشکافی پرامپت روایت تاریخی هرودوت
پرامپت زیر را بخوانید و هر یک از عناصر تشکیل‌دهنده آن (دستور کار، زمینه، داده ورودی، ویژگی خروجی) را به تفکیک مشخص کنید:

> «در نقش هرودوت، مورخ یونان باستان، نامه‌ای بنویس و در آن، واقعه جنگ ماراتن را از دیدگاه یک یونانی و با لحن و سبک نگارش آن دوره برای یک مورخ امروزی روایت کن.»

**راهنمای تحلیل:** پس از نوشتن پاسخ خود، اجزا را با الگوی استاندارد زیر بسنجید:
- **دستور کار:** نامه‌ای بنویس و واقعه جنگ ماراتن را روایت کن.
- **زمینه:** در نقش هرودوت، مورخ یونان باستان... از دیدگاه یک یونانی برای یک مورخ امروزی.
- **داده ورودی:** ندارد (از دانش درونی مدل استفاده می‌شود).
- **ویژگی‌های خروجی:** با لحن و سبک نگارش آن دوره.
