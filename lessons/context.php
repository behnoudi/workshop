### مؤلفه چهارم: مثال (Example)

در بخش «مثال‌» سعی کنید روشن‌ترین و مرتبط‌ترین نمونه‌ها را ارائه دهید تا هوش مصنوعی بتواند به طور دقیق درک کند که شما به دنبال چه نوع پاسخی هستید.

هرچه مثال‌های شما گویاتر باشند، احتمال دریافت پاسخ مطابق با انتظارات شما بیشتر خواهد بود.

> پنج شعار جذاب برای کارگاه آموزشی پیشنهاد بده **مثل «دانش، کلید موفقیت»**

