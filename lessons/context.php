### مؤلفه اول: پرسونا (Persona)

پرسونا تعیین می‌کند که هوش مصنوعی از چه منظری به موضوع نگاه کرده، با چه هویت و نگرشی با شما گفتگو کند و وظایف خود را انجام دهد.

با توصیف دقیق‌تر پرسونا، هوش مصنوعی را از قالب یک پاسخ‌دهنده‌ی معمولی خارج کرده و به یک هم‌صحبتی تبدیل می‌کنید که سبک گفتار و رفتار او کاملاً متناسب با انتظارات و نیازهای شماست. برخی از مواردی که با تعیین آن‌ها می‌توانید پرسونای هوش مصنوعی را مشخص کنید عبارتند از:

> **– شغل (Job):** شما معلم فیزیک هستید.  
> **– دانش (Knowledge):** شما در رشته فیزیک دانشمند هستید.  
> **– مهارت (Skill):** شما مهارت بالایی در «پرسش‌گری سقراطی» دارید.  
> **– رفتار (Behavior):** شما برای توضیح مفاهیم از مثال‌های ملموس روزمره استفاده می‌کنید.  
> **– نگرش (Attitude):**  
> **۱. کنجکاوی (Curiosity):** با پرسیدن سؤالات کوتاه، انگیزه یادگیری را در مخاطب بیدار می‌کنید.  
> **۲. همدلی (Empathy):** اگر مخاطب سؤالی را اشتباه جواب داد، بدون سرزنش او را راهنمایی می‌کنید.  
> **۳. فروتنی (Humility):** خود را دانای کل نمی‌دانید؛ اگر مخاطب موضوعی را متوجه نشد، لحن خود را ساده‌تر می‌کنید.  
> **۴. امیدواری (Hope):** همواره این حس را به مخاطب القا می‌کنید که با تلاش خود می‌تواند دشوارترین مسائل را هم حل کند.

**دستاوردهای تعیین پرسونا در پرامپت:**
- **ثبات در پاسخ‌دهی:** هوش مصنوعی در طول یک گفتگوی طولانی، لحن خود را گم نمی‌کند و تا آخر بر اساس همان پرسونا (مثلاً تواضع یا امیدواری) با کاربر تعامل خواهد داشت.
- **مناسب برای ربات‌های منتورینگ و همیاری:** این فریم‌ورک در طراحی چت‌بات‌های همیار و مشاور که قرار است با نوجوانان در ارتباط باشند، ایمنی اخلاقی بسیار بالایی ایجاد می‌کند.

