### مؤلفه دوم: مخاطب (Audience)

با تعیین دقیق مخاطب، هوش مصنوعی درک بهتری از سطح دانش، نیازها و انتظارات آن‌ها پیدا می‌کند. این امر منجر به تولید پاسخ‌هایی می‌شود که از نظر سطح پیچیدگی و جزئیات، برای مخاطب مناسب‌تر هستند.

در نتیجه، می‌توانید اطمینان حاصل کنید که اطلاعات ارائه شده به بهترین شکل ممکن به دست افراد مورد نظر می‌رسد.

> **– موقعیت و عنوان (Position):** مخاطبان مادرانِ دانش‌آموزانِ مقطع دبیرستان هستند.  
> **– سن (Age):** مخاطبان در دوران میان‌سالی هستند.  
> **– فرهنگ (Culture):** مخاطبان مادران خانواده‌های ایرانی با دغدغه‌های دینی هستند.  
> **– دانش (Knowledge):** مخاطبان مادران با تحصیلات دانشگاهی هستند.  
> **– مهارت (Skill):** مخاطبان در هنر آشپزی ماهر هستند.  
> **– نگرش (Attitude):** مخاطبان علاقه‌ی زیادی به جنبه‌های تخصصی موضوع دارند.  
> **– نیازهای خاص (Specific Needs):** مخاطبان دارای اختلال اضطرابی هستند.

---

### مؤلفه سوم: هدف (Goal)

هدف تعیین می‌کند دقیقاً چه انتظاری از هوش مصنوعی می‌رود و از سردرگمی یا ارائه‌ی پاسخ‌های نامربوط جلوگیری می‌کند.  
به عبارت دیگر، تعیین هدف مانند دادن یک نقشه راه به هوش مصنوعی است که به آن کمک می‌کند تا تلاش خود را در مسیر درست متمرکز کند و در نهایت، پاسخ‌های متناسب‌تری با نیازهای شما ارائه دهد.

> **– اطلاع‌رسانی (Inform):** ارائه‌ی گزارش دقیق آمار فروش ماهانه  
> **– آموزش (Educate):** آموزش نحوه‌ی نصب نرم‌افزار جدید  
> **– متقاعدسازی (Persuade):** متقاعد کردن مخاطبان به خرید محصول جدید  
> **– گفتگو (Discuss):** بحث و گفتگو با مخاطبان درباره‌ی اراده‌ی آزاد  
> **– سرگرمی (Entertain):** نوشتن داستانی مهیج و پر از ماجراجویی  
> **– انگیزش (Motivate):** برانگیختن شور و اشتیاق در شنوندگان

