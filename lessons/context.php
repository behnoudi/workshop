### تمرین‌های تثبیت مهارت

#### تمرین ۱: مقایسه پرامپت ساده و پرامپت بهینه‌شده
هریک از دو پرامپت زیر را به هوش مصنوعی بدهید:

**پرامپت ساده:**
> یک مقاله درباره انقلاب صنعتی بنویسید.

**پرامپت بهینه:**
> **# نقش:** شما استاد تاریخ در دانشگاه هستید.  
> **# مخاطب:** مدیران اجرایی شرکت‌ها هستند.  
> **# هدف:** مخاطب را متقاعد کنید که آموزه‌های انقلاب صنعتی برای کسب و کارهای امروزی هم حیاتی است.  
> **# دستور کار:** یک مقاله درباره «درس‌ها و الگوهای انقلاب صنعتی برای کسب و کارهای مدرن» بنویسید.

خروجی‌ها را با هم مقایسه کنید. افزودن (نقش، مخاطب، هدف) چه تأثیری بر کیفیت، لحن و عمق خروجی داشت؟

---

#### تمرین ۲: بهینه‌سازی پرامپت با افزودن زمینه
پرامپت زیر را با افزودن زمینه (نقش، مخاطب، هدف و محدودیت‌ها) بهینه کنید:
> یک برنامه غذایی روزانه با مجموع ۱۶۰۰ کالری پیشنهاد دهید.

**راهنمایی:** به این فکر کنید که این برنامه غذایی برای چه کسی است؟ (مثلاً: یک دانش‌آموز دبیرستانیِ پرتحرک یا یک معلم که بیشترِ روز پشت میز می‌نشیند؟)، آیا محدودیت یا ترجیح خاصی دارد؟ (مثلاً: غذاهای سنتی ایرانی، گیاه‌خواری یا حساسیت به گلوتن؟) و هدف او چیست؟ (کاهش وزن، تثبیت وزن یا افزایش انرژی؟).
